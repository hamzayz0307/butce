export let LANG = 'tr';
export function setLang(l) { LANG = l === 'en' ? 'en' : 'tr'; }

export function t(k, v = {}) {
  const s = I18N[LANG][k] ?? I18N.tr[k] ?? k;
  return s.replace(/\{(\w+)\}/g, (_, x) => (v[x] ?? ''));
}

export const LOC = () => (LANG === 'en' ? 'en-US' : 'tr-TR');
